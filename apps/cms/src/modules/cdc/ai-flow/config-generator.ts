/**
 * AI Flow config generator — produces a deployment {@link EnvironmentConfig}
 * for a given CDC approach and deployment target (ClickHouse CDC —
 * task 11.1; design "AI Flow Engine" §5 and "Deployment Topology",
 * Requirements 7.1, 7.2).
 *
 * The AI Flow Engine deploys the CDC system across LumiBase's dual-runtime
 * architecture, so a deployment is described by two axes:
 *
 *   - **approach** ({@link CdcConnectorType}) — which replication strategy
 *     the pipeline uses (`debezium_kafka`, `materialized_engine`, or
 *     `airbyte`). This selects the approach-specific environment variables
 *     and stateful services.
 *   - **target** ({@link DeploymentTarget}) — where the components run. This
 *     scopes *which* components are part of this deployment:
 *       - `docker_compose` (or managed services) hosts the **full stateful
 *         stack** for the approach — Kafka_Broker, Debezium_Connector,
 *         ClickHouse_Sink, Materialized_Engine, Airbyte_Connector (only the
 *         subset relevant to the approach). These require long-lived TCP
 *         connections, persistent buffers, and replication-slot ownership.
 *       - `cloudflare_workers` hosts **only the lightweight edge
 *         components** — the CDC API/control-plane endpoints and the
 *         Cache_Invalidator. A Workers deployment NEVER includes stateful
 *         connectors, the Kafka message bus, or replication engines; it
 *         always depends on a companion `docker_compose`/managed-services
 *         deployment for the stateful stack, reached over HTTPS.
 *
 * This module is **pure**: {@link generateConfig} performs no I/O and holds
 * no state. It is a referentially-transparent mapping from
 * `(approach, target)` to an {@link EnvironmentConfig}, so task 11.5
 * (Property 17 — every required variable is present for each approach +
 * target combination) can exercise it deterministically.
 *
 * Downstream consumers:
 *   - task 11.2 (`env-validator.ts`) validates submitted values against the
 *     {@link EnvVarDefinition.validation} rules surfaced here.
 *   - task 11.3 (`deployment-orchestrator.ts`) provisions the
 *     {@link EnvironmentConfig.services} listed here.
 *
 * Validates: Requirements 7.1, 7.2
 */

import type { CdcConnectorType } from '../connectors/types';

// ── target axis (design "Deployment Topology" / §5) ─────────────────────

/**
 * Where a CDC deployment's components run.
 *
 *   - `'docker_compose'`   → full stateful stack for the approach (Kafka,
 *     Debezium, ClickHouse, Materialized Engine, Airbyte), via Docker
 *     Compose containers on a shared network or external managed services
 *     (Confluent Cloud / ClickHouse Cloud / Airbyte Cloud).
 *   - `'cloudflare_workers'` → edge components ONLY (CDC API/control-plane
 *     endpoints + Cache_Invalidator). Cannot host stateful connectors, the
 *     message bus, or replication engines.
 */
export type DeploymentTarget = 'docker_compose' | 'cloudflare_workers';

// ── environment variable model (task 11.1) ──────────────────────────────

/**
 * Environment-variable key naming rule, kept in sync with the `key` regex
 * of `EnvVarSchema` in `packages/shared/src/schemas/cdc.ts`
 * (`/^[A-Z_][A-Z0-9_]*$/`). Every {@link EnvVarDefinition.key} generated by
 * this module conforms to this pattern so generated configs round-trip
 * cleanly through that shared schema.
 */
export const ENV_VAR_KEY_PATTERN = /^[A-Z_][A-Z0-9_]*$/;

/**
 * A machine-checkable validation rule for an environment variable value,
 * plus a human-readable description of the constraint. Task 11.2's
 * env-validator uses these fields to identify invalid values and report the
 * specific violated rule (Req 7.4, 7.5).
 *
 * Fields are additive — a definition may combine, for example, a `pattern`
 * with a human-readable `rule`. All fields except `rule` are optional.
 */
export interface EnvVarValidation {
  /** Human-readable description of the constraint (always present). */
  readonly rule: string;

  /**
   * Optional regular-expression source (string form) the value must match
   * in full. Stored as a string so the definition stays serialisable.
   */
  readonly pattern?: string;

  /** Optional set of allowed values (for enumerated variables). */
  readonly enum?: readonly string[];

  /**
   * Optional inclusive lower bound. Interpreted as a numeric minimum for
   * integer variables, or a minimum length for string variables.
   */
  readonly min?: number;

  /**
   * Optional inclusive upper bound. Interpreted as a numeric maximum for
   * integer variables, or a maximum length for string variables.
   */
  readonly max?: number;
}

/**
 * Definition of a single environment variable required (or optional) for a
 * deployment. Carries everything the documentation (task 15.1), the
 * env-validator (task 11.2), and the deployment orchestrator (task 11.3)
 * need: the key, a human-readable description, an optional default, whether
 * it is required, and the validation rule its value must satisfy.
 */
export interface EnvVarDefinition {
  /** UPPER_SNAKE_CASE variable name (matches {@link ENV_VAR_KEY_PATTERN}). */
  readonly key: string;

  /** Human-readable description of what the variable controls. */
  readonly description: string;

  /**
   * Sensible default value, when one exists. Absent (`undefined`) when the
   * operator MUST supply a value (e.g. connection strings, secrets).
   */
  readonly default?: string;

  /** Whether a value MUST be present for the deployment to be valid. */
  readonly required: boolean;

  /** Validation rule the value must satisfy. */
  readonly validation: EnvVarValidation;
}

// ── service model (task 11.1) ───────────────────────────────────────────

/**
 * Definition of a single service that is part of a deployment. Used by the
 * deployment orchestrator (task 11.3) to provision and health-check each
 * component, and by the documentation generator (task 15.1).
 */
export interface ServiceDefinition {
  /** Canonical service identifier, e.g. `'kafka_broker'`. */
  readonly name: string;

  /** Human-readable display name, e.g. `'Kafka Broker'`. */
  readonly displayName: string;

  /** Short description of the service's role in the pipeline. */
  readonly description: string;

  /**
   * Whether this is a **stateful** stack component (requires long-lived
   * connections / persistent storage / replication-slot ownership) as
   * opposed to a lightweight **edge** component. Stateful services only
   * appear in `docker_compose` deployments; edge services only appear in
   * `cloudflare_workers` deployments.
   */
  readonly stateful: boolean;

  /**
   * Container image (with tag) for `docker_compose` targets. Absent for
   * edge components (which run as Cloudflare Workers) and for logical
   * services that run inside another container (e.g. the Materialized
   * Engine runs inside ClickHouse).
   */
  readonly image?: string;

  /** Ports the service exposes on the shared network (docker_compose). */
  readonly ports?: readonly number[];

  /** Names of other services this service depends on (start ordering). */
  readonly dependsOn?: readonly string[];
}

// ── environment config (design §5) ──────────────────────────────────────

/**
 * Complete deployment configuration for one `(approach, target)`
 * combination — the output of {@link generateConfig}. Mirrors the
 * `EnvironmentConfig` interface in the design's "AI Flow Engine" section.
 */
export interface EnvironmentConfig {
  /** The CDC replication approach this config targets. */
  readonly approach: CdcConnectorType;

  /** Where the components in this config run. */
  readonly target: DeploymentTarget;

  /** All environment variables (required and optional) for the deployment. */
  readonly variables: readonly EnvVarDefinition[];

  /** The services provisioned by this deployment, scoped by target. */
  readonly services: readonly ServiceDefinition[];
}

// ── reusable validation builders ────────────────────────────────────────

/** A non-empty free-form string value. */
const NON_EMPTY: EnvVarValidation = {
  rule: 'Must be a non-empty string',
  min: 1,
};

/** A value that must be a connection URL with one of the given schemes. */
function urlValidation(schemes: readonly string[], note?: string): EnvVarValidation {
  const alternation = schemes.length === 1 ? schemes[0] : `(?:${schemes.join('|')})`;
  const schemeList = schemes.map((s) => `${s}://`).join(' or ');
  return {
    rule: `Must be a valid ${schemeList} connection URL${note ? ` (${note})` : ''}`,
    pattern: `^${alternation}:\\/\\/.+`,
  };
}

/** An integer value constrained to the inclusive range [min, max]. */
function intRangeValidation(min: number, max: number): EnvVarValidation {
  return {
    rule: `Must be an integer between ${min} and ${max} (inclusive)`,
    pattern: '^[0-9]+$',
    min,
    max,
  };
}

/** A positive integer value (≥ 1) with no explicit upper bound. */
function positiveIntValidation(): EnvVarValidation {
  return {
    rule: 'Must be a positive integer (≥ 1)',
    pattern: '^[1-9][0-9]*$',
    min: 1,
  };
}

/** A value restricted to a fixed set of choices. */
function enumValidation(values: readonly string[]): EnvVarValidation {
  return {
    rule: `Must be one of: ${values.join(', ')}`,
    enum: values,
  };
}

