// ── public API ───────────────────────────────────────────────────────────

/**
 * Generate the complete {@link EnvironmentConfig} for a CDC `approach` and
 * deployment `target` (Req 7.1).
 *
 * The result is scoped by target (Req 7.2):
 *
 *   - **`docker_compose`** → the full stateful stack for the approach
 *     (connection variables + approach-specific tuning, and the
 *     Kafka/Debezium/ClickHouse/Materialized/Airbyte services relevant to
 *     the approach).
 *   - **`cloudflare_workers`** → edge components ONLY (the CDC
 *     API/control-plane and Cache_Invalidator, with their HTTPS/Redis
 *     variables). Stateful connectors, the message bus, and replication
 *     engines are explicitly excluded — those live in a companion
 *     `docker_compose`/managed-services deployment.
 *
 * Universal identity variables (`CDC_PIPELINE_NAME`, `CDC_APPROACH`,
 * `CDC_DEPLOYMENT_TARGET`) are always present so both halves of a split
 * deployment can be correlated.
 *
 * The function is pure and total: every valid `(approach, target)` pair
 * yields a config whose required variables are all present, satisfying
 * Property 17 (task 11.5).
 *
 * @param approach - The CDC replication strategy.
 * @param target - Where the components run.
 * @returns The deployment configuration for this combination.
 */
export function generateConfig(
  approach: CdcConnectorType,
  target: DeploymentTarget,
): EnvironmentConfig {
  const variables: EnvVarDefinition[] = [...universalVars(approach, target)];
  let services: readonly ServiceDefinition[];

  if (target === 'docker_compose') {
    // Full stateful stack for the approach.
    variables.push(...statefulCommonVars(), ...statefulApproachVars(approach));
    services = STATEFUL_SERVICES_BY_APPROACH[approach];
  } else {
    // Edge components only — exclude stateful connectors, the message bus,
    // and replication engines (Req 7.2).
    variables.push(...edgeVars());
    services = EDGE_SERVICES;
  }

  return { approach, target, variables, services };
}

/**
 * Convenience helper returning the keys of every **required** variable in a
 * generated config, in declaration order. Useful for completeness checks
 * (Property 17) and documentation.
 *
 * @param config - A config produced by {@link generateConfig}.
 * @returns The required variable keys.
 */
export function requiredEnvVarKeys(config: EnvironmentConfig): string[] {
  return config.variables.filter((v) => v.required).map((v) => v.key);
}
