/**
 * Usage emitter — contracts.
 *
 * The CMS reports what a request or a background job consumed at a fixed set
 * of points: one event per API or delivery request, plus service events for
 * storage writes, membership changes, agent runs, model tokens and outbound
 * email. An operator who registers an emitter receives those events already
 * attributed to a site and its organization; with nothing registered the CMS
 * never builds an event at all.
 *
 * Separate from the opt-in anonymous telemetry: different payload, different
 * switch, no shared storage. Events carry no content and no personal data —
 * `attributes` holds classification values only (surface, status class, model
 * id), never a path, a body, an address or a user id.
 */

import type { SeamContext, TenantRef } from './index';

/** Unit of {@link UsageEvent.quantity}. */
export type UsageUnit = 'count' | 'bytes' | 'tokens' | 'ms';

/** Event kinds the CMS itself emits. The field is open: implementations must tolerate others. */
export const USAGE_KINDS = {
  /** One request on the authenticated API (REST, GraphQL, MCP). `count`. */
  apiRequest: 'api.request',
  /** One request on the public delivery API. `count`. */
  deliveryRequest: 'delivery.request',
  /**
   * Bytes written to (positive) or released from (negative) object storage.
   * A signed delta in `bytes`; integrating it over time is the consumer's job.
   */
  storageBytes: 'storage.bytes',
  /** Organization membership added (+1) or removed (-1). `count`. */
  seatChange: 'seat.change',
  /** One agent run reached a terminal state. `count`. */
  agentRun: 'agent.run',
  /** Tokens reported by a model provider for one call. `tokens`. */
  aiTokens: 'ai.tokens',
  /** Recipients of one outbound email accepted by the transport. `count`. */
  emailSent: 'email.sent',
} as const;

export type UsageKind = (typeof USAGE_KINDS)[keyof typeof USAGE_KINDS];

/** Classification values only. No content, no personal data. */
export type UsageAttributes = Readonly<Record<string, string | number | boolean>>;

export interface UsageEvent {
  /**
   * Idempotency key: a uuidv7 generated by the CMS where the event is
   * produced. A consumer that sees the same id twice must count it once —
   * transports in front of it may deliver at least once.
   */
  id: string;
  /** Namespaced, open key — see {@link USAGE_KINDS}. */
  kind: string;
  /** Site and organization at the moment of the event, not at aggregation time. */
  tenant: TenantRef;
  /** May be negative for signed deltas (`storage.bytes`, `seat.change`). */
  quantity: number;
  unit: UsageUnit;
  /** ISO 8601, UTC. */
  occurredAt: string;
  attributes?: UsageAttributes;
}

export interface UsageEmitter<TRuntime = unknown> {
  /**
   * Hand one event over. Synchronous and must not throw: the CMS calls it
   * after the response is decided, and treats a throw as a lost event. Buffer
   * here; do the I/O in {@link flush}.
   */
  emit(event: UsageEvent): void;
  /**
   * Called once per request (inside `waitUntil` on Workers, after the response
   * on Node) and once at the end of each background job. Never awaited by the
   * response. A rejection is logged and otherwise ignored.
   */
  flush(ctx: SeamContext<TRuntime>): Promise<void>;
}
