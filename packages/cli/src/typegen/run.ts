import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import {
  filterManifest,
  generateGraphQLSdl,
  generateOpenApi,
  generateZod,
  type TypegenManifest,
} from '@lumibase/sdk';
import { fetchTypegenManifestIfChanged, type Connection, type RequestOptions } from '../api.js';
import type { ResolvedConfig } from '../config.js';
import { CliError } from '../errors.js';
import type { TypegenConfig, TypegenLiveSource, TypegenTarget } from '../typegen-config.js';
import { log } from '../utils/log.js';
import { DEFAULT_IMPORT_FROM, renderTypes } from '../commands/types.js';

/**
 * Multi-config, multi-target runner behind `lumibase types` when a
 * `lumibase.typegen.config.*` file is present (#753).
 *
 * Every config is planned up front (sources resolved, output paths fixed),
 * each distinct source is fetched once per run, and every target is rendered
 * from that one manifest — so two configs produce two outputs in one run.
 */

const TS_BANNER = [
  '// Generated by `lumibase types` — do not edit by hand.',
  '// Re-run the command after changing collections or fields.',
].join('\n');
const SDL_BANNER = [
  '# Generated by `lumibase types` — do not edit by hand.',
  '# Re-run the command after changing collections or fields.',
].join('\n');

/** Renders one target. Deterministic: no host, site id, or timestamp in any output. */
export function renderTarget(target: TypegenTarget, manifest: TypegenManifest): string {
  switch (target.type) {
    case 'ts':
      return renderTypes(manifest, {
        branded: target.branded ?? true,
        importFrom: target.importFrom ?? DEFAULT_IMPORT_FROM,
      });
    case 'zod':
      return `${TS_BANNER}\n\n${generateZod(manifest, { importSource: target.importFrom }).trimEnd()}\n`;
    case 'graphql-sdl':
      return `${SDL_BANNER}\n\n${generateGraphQLSdl(manifest).trimEnd()}\n`;
    case 'openapi':
      return `${JSON.stringify(generateOpenApi(manifest, { title: target.title, version: target.version }), null, 2)}\n`;
    case 'manifest': {
      // The site id is dropped for the same reason as the banners: `--check`
      // in CI runs against another instance.
      const { site: _site, ...portable } = manifest;
      return `${JSON.stringify(portable, null, 2)}\n`;
    }
  }
}

// ---------------------------------------------------------------------------
// Sources
// ---------------------------------------------------------------------------

export interface ManifestSource {
  /** Identifies the source; configs with equal keys share one fetch. */
  key: string;
  label: string;
  /** Full load. Also records the state `poll` compares against. */
  load(): Promise<TypegenManifest>;
  /** The new manifest when it changed since the last load/poll, else null. */
  poll(): Promise<TypegenManifest | null>;
}

function contentHash(manifest: TypegenManifest): string {
  return createHash('sha256').update(JSON.stringify(manifest)).digest('hex');
}

export function liveSource(connection: Connection, request?: RequestOptions): ManifestSource {
  let etag: string | undefined;
  let hash: string | undefined;

  const fetchOnce = async (conditional: boolean): Promise<TypegenManifest | null> => {
    const result = await fetchTypegenManifestIfChanged(connection, {}, conditional ? etag : undefined, request);
    if (result.status === 'not-modified') return null;
    etag = result.etag;
    const next = contentHash(result.manifest);
    // A server without ETag support answers 200 every time — compare content.
    if (conditional && next === hash) return null;
    hash = next;
    return result.manifest;
  };

  return {
    key: `live:${connection.url}|${connection.siteId}|${createHash('sha256').update(connection.token).digest('hex').slice(0, 12)}`,
    label: `${connection.url} (site ${connection.siteId})`,
    load: async () => (await fetchOnce(false)) as TypegenManifest,
    poll: () => fetchOnce(true),
  };
}

/** Reads a saved manifest: either the raw manifest or the API's `{ data }` envelope. */
export function readManifestFile(path: string): TypegenManifest {
  let parsed: unknown;
  try {
    parsed = JSON.parse(readFileSync(path, 'utf8'));
  } catch (err) {
    throw new CliError(`Could not read manifest ${path}: ${err instanceof Error ? err.message : String(err)}`);
  }
  const candidate =
    typeof parsed === 'object' && parsed !== null && 'data' in parsed
      ? (parsed as { data: unknown }).data
      : parsed;
  if (
    typeof candidate !== 'object' ||
    candidate === null ||
    !Array.isArray((candidate as { collections?: unknown }).collections)
  ) {
    throw new CliError(`${path} is not a typegen manifest (no "collections" array).`);
  }
  const manifest = candidate as Partial<TypegenManifest> & Pick<TypegenManifest, 'collections'>;
  return { version: manifest.version ?? 0, site: manifest.site ?? '', collections: manifest.collections };
}

export function fileSource(path: string): ManifestSource {
  let stamp: string | undefined;
  let hash: string | undefined;

  const statStamp = (): string => {
    const stats = statSync(path);
    return `${stats.mtimeMs}:${stats.size}`;
  };

  return {
    key: `file:${path}`,
    label: path,
    load: async () => {
      stamp = statStamp();
      const manifest = readManifestFile(path);
      hash = contentHash(manifest);
      return manifest;
    },
    poll: async () => {
      const current = statStamp();
      if (current === stamp) return null;
      stamp = current;
      const manifest = readManifestFile(path);
      const next = contentHash(manifest);
      if (next === hash) return null;
      hash = next;
      return manifest;
    },
  };
}

// ---------------------------------------------------------------------------
// Planning
// ---------------------------------------------------------------------------

export interface PlannedOutput {
  target: TypegenTarget;
  path: string;
}

export interface PlannedConfig {
  label: string;
  config: TypegenConfig;
  source: ManifestSource;
  outputs: PlannedOutput[];
}

export interface PlanOptions {
  /** Directory config-relative paths resolve against. */
  dir: string;
  env: NodeJS.ProcessEnv;
  /** Flag > env > lumibase.config.json fallback for live sources. */
  fallback: ResolvedConfig;
  request?: RequestOptions;
}

function fromEnv(env: NodeJS.ProcessEnv, name: string | undefined, what: string, label: string): string | undefined {
  if (!name) return undefined;
  const value = env[name];
  if (!value) {
    throw new CliError(`${label}: ${what} environment variable ${name} is not set.`);
  }
  return value;
}

function resolveConnection(source: TypegenLiveSource, options: PlanOptions, label: string): Connection {
  const { env, fallback } = options;
  const url = source.url ?? fromEnv(env, source.urlEnv, 'the URL', label) ?? fallback.url;
  const siteId = source.site ?? fromEnv(env, source.siteEnv, 'the site id', label) ?? fallback.siteId;
  const token = fromEnv(env, source.tokenEnv, 'the token', label) ?? fallback.token;

  const missing: string[] = [];
  if (!url) missing.push('url (source.url / source.urlEnv / LUMIBASE_URL)');
  if (!siteId) missing.push('site (source.site / source.siteEnv / LUMIBASE_SITE_ID)');
  if (!token) missing.push('token (source.tokenEnv / LUMIBASE_TOKEN)');
  if (missing.length > 0) {
    throw new CliError(
      `${label}: missing connection settings: ${missing.join(', ')}.`,
      'Or point the config at a saved manifest: source: { manifest: "./lumibase.manifest.json" }.',
    );
  }

  return {
    url: (url as string).replace(/\/$/, ''),
    siteId: siteId as string,
    token: token as string,
  };
}

export function planTypegen(configs: TypegenConfig[], options: PlanOptions): PlannedConfig[] {
  const sources = new Map<string, ManifestSource>();
  const share = (source: ManifestSource): ManifestSource => {
    const existing = sources.get(source.key);
    if (existing) return existing;
    sources.set(source.key, source);
    return source;
  };

  return configs.map((config, index) => {
    const label = config.name ?? `config #${index + 1}`;
    const raw = config.source ?? {};
    const source =
      'manifest' in raw
        ? share(fileSource(resolve(options.dir, raw.manifest)))
        : share(liveSource(resolveConnection(raw, options, label), options.request));
    return {
      label,
      config,
      source,
      outputs: config.targets.map((target) => ({ target, path: resolve(options.dir, target.out) })),
    };
  });
}

// ---------------------------------------------------------------------------
// Running
// ---------------------------------------------------------------------------

export type OutputStatus = 'written' | 'unchanged' | 'stale' | 'missing' | 'up-to-date';

export interface OutputResult {
  config: string;
  type: TypegenTarget['type'];
  path: string;
  status: OutputStatus;
}

export interface RunTypegenOptions {
  /** Compare only; never write. Throws when anything is stale or missing. */
  check?: boolean;
  /** Base for the paths printed in log lines. */
  cwd: string;
}

/** Renders and writes (or checks) every output of the given planned configs. */
export function emitOutputs(
  planned: PlannedConfig,
  manifest: TypegenManifest,
  options: RunTypegenOptions,
): OutputResult[] {
  const filtered = filterManifest(manifest, planned.config);
  const results: OutputResult[] = [];

  for (const output of planned.outputs) {
    const generated = renderTarget(output.target, filtered);
    const display = relative(options.cwd, output.path) || output.path;
    const existing = existsSync(output.path) ? readFileSync(output.path, 'utf8') : undefined;
    const base = { config: planned.label, type: output.target.type, path: output.path };

    if (options.check) {
      const status: OutputStatus =
        existing === undefined ? 'missing' : existing === generated ? 'up-to-date' : 'stale';
      results.push({ ...base, status });
      if (status === 'up-to-date') log.success(`${display} is up to date (${output.target.type}).`);
      else log.error(`${display} is ${status === 'missing' ? 'missing' : 'out of date'} (${output.target.type}).`);
      continue;
    }

    if (existing === generated) {
      results.push({ ...base, status: 'unchanged' });
      log.success(`${display} already up to date (${output.target.type}).`);
      continue;
    }

    mkdirSync(dirname(output.path), { recursive: true });
    writeFileSync(output.path, generated, 'utf8');
    results.push({ ...base, status: 'written' });
    log.success(`Wrote ${display} — ${output.target.type}, ${filtered.collections.length} collections.`);
  }

  return results;
}

/** One full run over every config: each distinct source is loaded exactly once. */
export async function runTypegen(plan: PlannedConfig[], options: RunTypegenOptions): Promise<OutputResult[]> {
  const loaded = new Map<ManifestSource, TypegenManifest>();
  const results: OutputResult[] = [];

  for (const planned of plan) {
    let manifest = loaded.get(planned.source);
    if (!manifest) {
      manifest = await planned.source.load();
      loaded.set(planned.source, manifest);
    }
    results.push(...emitOutputs(planned, manifest, options));
  }

  if (options.check) {
    const failing = results.filter((result) => result.status === 'stale' || result.status === 'missing');
    if (failing.length > 0) {
      throw new CliError(
        `${failing.length} of ${results.length} generated file(s) are missing or out of date.`,
        'Run `lumibase types` and commit the result.',
      );
    }
  }

  return results;
}

// ---------------------------------------------------------------------------
// Watching
// ---------------------------------------------------------------------------

export interface WatchOptions {
  cwd: string;
  /** Poll interval while healthy. Default 2000 ms. */
  intervalMs?: number;
  /** Upper bound of the error backoff. Default 60000 ms. */
  maxBackoffMs?: number;
  signal?: AbortSignal;
  /** Injected for tests. */
  sleep?: (ms: number, signal?: AbortSignal) => Promise<void>;
  /** Called after every poll round (tests use it to stop the loop). */
  onRound?: (round: { regenerated: OutputResult[]; error?: unknown; nextDelayMs: number }) => void;
}

export const DEFAULT_WATCH_INTERVAL_MS = 2_000;
export const DEFAULT_WATCH_MAX_BACKOFF_MS = 60_000;

function defaultSleep(ms: number, signal?: AbortSignal): Promise<void> {
  return new Promise((resolveSleep) => {
    if (signal?.aborted) return resolveSleep();
    const timer = setTimeout(resolveSleep, ms);
    signal?.addEventListener(
      'abort',
      () => {
        clearTimeout(timer);
        resolveSleep();
      },
      { once: true },
    );
  });
}

/**
 * Runs once, then polls every source and regenerates only the configs whose
 * source changed. A live source is polled with `If-None-Match` (304 = no
 * work); a manifest file is checked by mtime/size, then by content. Failures
 * back off exponentially up to `maxBackoffMs` and reset on the next success.
 */
export async function watchTypegen(plan: PlannedConfig[], options: WatchOptions): Promise<void> {
  const interval = options.intervalMs ?? DEFAULT_WATCH_INTERVAL_MS;
  const maxBackoff = options.maxBackoffMs ?? DEFAULT_WATCH_MAX_BACKOFF_MS;
  const sleep = options.sleep ?? defaultSleep;
  const sources = [...new Set(plan.map((planned) => planned.source))];

  await runTypegen(plan, { cwd: options.cwd });
  log.info(`Watching ${sources.length} source(s) for schema changes — Ctrl+C to stop.`);

  let delay = interval;
  while (!options.signal?.aborted) {
    await sleep(delay, options.signal);
    if (options.signal?.aborted) break;

    const regenerated: OutputResult[] = [];
    let error: unknown;
    for (const source of sources) {
      try {
        const manifest = await source.poll();
        if (!manifest) continue;
        log.info(`Schema changed at ${source.label}.`);
        for (const planned of plan.filter((candidate) => candidate.source === source)) {
          regenerated.push(...emitOutputs(planned, manifest, { cwd: options.cwd }));
        }
      } catch (err) {
        error = err;
        log.warn(`Polling ${source.label} failed: ${err instanceof Error ? err.message : String(err)}`);
      }
    }

    delay = error ? Math.min(Math.max(delay, interval) * 2, maxBackoff) : interval;
    if (error) log.dim(`  Retrying in ${Math.round(delay / 1000)}s.`);
    options.onRound?.({ regenerated, error, nextDelayMs: delay });
  }
}
