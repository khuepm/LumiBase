import type { TypegenCollection, TypegenField, TypegenManifest } from './types';
import { fieldShape, hasIntegerPrimaryKey, isNullable, relationsOf } from './shared';

/** A JSON Schema 2020-12 object as embedded in an OpenAPI 3.1 document. */
export type JsonSchema = Record<string, unknown>;

export interface GenerateOpenApiOptions {
  /** `info.title`. Defaults to `LumiBase content schemas`. */
  title?: string;
  /** `info.version`. Defaults to `manifest-v<manifest.version>`. */
  version?: string;
}

export interface OpenApiComponentsDocument {
  openapi: '3.1.0';
  info: { title: string; version: string; description: string };
  components: { schemas: Record<string, JsonSchema> };
}

/**
 * An OpenAPI 3.1 `components/schemas` document built from the typegen
 * manifest — offline, with no caller in mind: every collection and field in
 * the manifest is documented, encrypted values may be masked (`'***'`).
 *
 * Component names and shapes follow the live per-caller document
 * (`GET /api/v1/openapi.json`) so either can feed the same client generator:
 * `<collection>.Fields` (user fields), `<collection>.Item` (the stored row —
 * system columns at the top level, user fields under `data`),
 * `<collection>.Projection` (the flat `?fields=` shape),
 * `<collection>.CreateInput` / `.UpdateInput`, plus `{ data, meta }`
 * envelopes `<collection>.Response` / `.ListResponse` and the shared
 * `PaginationMeta` / `ErrorResponse`.
 */
export function generateOpenApi(
  manifest: TypegenManifest,
  options: GenerateOpenApiOptions = {},
): OpenApiComponentsDocument {
  const byName = new Map(manifest.collections.map((collection) => [collection.name, collection]));

  // Component keys must match `^[a-zA-Z0-9.\-_]+$`; disambiguate collisions.
  const bases = new Map<string, string>();
  const taken = new Set<string>();
  for (const collection of manifest.collections) {
    const raw = collection.name.replace(/[^a-zA-Z0-9._-]/g, '_');
    let base = raw;
    for (let n = 2; taken.has(base); n += 1) base = `${raw}_${n}`;
    taken.add(base);
    bases.set(collection.name, base);
  }

  const ctx: SchemaContext = {
    primaryKeySchema: (name) =>
      hasIntegerPrimaryKey(byName.get(name)) ? { type: 'integer' } : { type: 'string' },
    projectionRef: (name) => {
      const base = bases.get(name);
      return base ? `#/components/schemas/${base}.Projection` : null;
    },
  };

  const schemas: Record<string, JsonSchema> = {
    ErrorObject: {
      type: 'object',
      properties: { code: { type: 'string' }, message: { type: 'string' } },
      required: ['code'],
    },
    ErrorResponse: {
      type: 'object',
      properties: { errors: { type: 'array', items: { $ref: '#/components/schemas/ErrorObject' } } },
      required: ['errors'],
    },
    PaginationMeta: {
      type: 'object',
      properties: {
        total: { type: 'integer', minimum: 0, description: 'Omitted when the request passed `meta=none`.' },
        limit: { type: 'integer', minimum: 1, maximum: 200 },
        offset: { type: 'integer', minimum: 0 },
      },
      required: ['limit', 'offset'],
    },
  };

  for (const collection of manifest.collections) {
    addCollectionSchemas(schemas, collection, bases.get(collection.name) as string, ctx);
  }

  return {
    openapi: '3.1.0',
    info: {
      title: options.title ?? 'LumiBase content schemas',
      version: options.version ?? `manifest-v${manifest.version}`,
      description:
        'Component schemas generated by `lumibase types` from the typegen manifest. ' +
        'For paths and a per-caller view, use the live document at /api/v1/openapi.json.',
    },
    components: { schemas },
  };
}

interface SchemaContext {
  primaryKeySchema: (collection: string) => JsonSchema;
  projectionRef: (collection: string) => string | null;
}

type Shape = 'item' | 'projection' | 'input';

const timestamp: JsonSchema = { type: 'string', format: 'date-time' };
const nullableTimestamp: JsonSchema = { type: ['string', 'null'], format: 'date-time' };
const nullableString: JsonSchema = { type: ['string', 'null'] };
const expandedObject: JsonSchema = {
  type: 'object',
  description: 'Expanded record (requested with `fields=<name>.*`).',
};
const fileId: JsonSchema = { type: 'string', description: 'File id (`/api/v1/files/{id}`).' };

/** Storage type → JSON Schema; mirrors the TS generator's scalar table. */
const FIELD_TYPE_JSON_SCHEMA: Readonly<Record<string, JsonSchema>> = {
  string: { type: 'string' },
  text: { type: 'string' },
  hash: { type: 'string' },
  csv: { type: 'string' },
  integer: { type: 'integer' },
  bigInteger: { type: 'integer', format: 'int64' },
  decimal: { type: 'number' },
  float: { type: 'number' },
  boolean: { type: 'boolean' },
  json: {},
  uuid: { type: 'string', format: 'uuid' },
  date: { type: 'string', format: 'date' },
  datetime: { type: 'string', format: 'date-time' },
  dateTime: { type: 'string', format: 'date-time' },
  time: { type: 'string', format: 'time' },
  timestamp: { type: 'string', format: 'date-time' },
  geometry: { type: 'object', additionalProperties: true, description: 'GeoJSON geometry object.' },
};

function withNull(schema: JsonSchema): JsonSchema {
  if (Object.keys(schema).length === 0) return schema; // `{}` already accepts null
  const type = schema['type'];
  if (typeof type === 'string' && !('enum' in schema)) return { ...schema, type: [type, 'null'] };
  if (typeof type === 'string' && Array.isArray(schema['enum'])) {
    return { ...schema, type: [type, 'null'], enum: [...(schema['enum'] as unknown[]), null] };
  }
  return { anyOf: [schema, { type: 'null' }] };
}

function referenceOrId(target: string, ctx: SchemaContext, shape: Shape): JsonSchema {
  const id = ctx.primaryKeySchema(target);
  if (shape !== 'projection') return id;
  const ref = ctx.projectionRef(target);
  return ref ? { anyOf: [id, { $ref: ref }] } : { anyOf: [id, expandedObject] };
}

/** JSON Schema for one user field, or null when it has no wire value (a bare alias). */
function fieldSchema(
  field: TypegenField,
  collection: TypegenCollection,
  ctx: SchemaContext,
  shape: Shape,
): JsonSchema | null {
  const relation = relationsOf(collection).find((candidate) => candidate.field === field.name);
  const kind = fieldShape(field);
  let schema: JsonSchema;

  if (field.kind === 'm2o' && field.target) {
    schema = referenceOrId(field.target, ctx, shape);
  } else if (kind.kind === 'to-many' || (relation && (relation.kind === 'o2m' || relation.kind === 'm2m'))) {
    const target = kind.kind === 'to-many' ? kind.target : (relation?.target as string);
    schema = { type: 'array', items: referenceOrId(target, ctx, shape) };
  } else if (kind.kind === 'm2a' || relation?.kind === 'm2a') {
    schema = {
      type: 'array',
      items: {
        type: 'object',
        properties: { collection: { type: 'string' }, item: {} },
        required: ['collection', 'item'],
      },
    };
  } else if (kind.kind === 'localized') {
    schema = {
      type: 'object',
      description: 'Per-locale values keyed by locale code (e.g. `{ "en": "…", "vi": "…" }`).',
      additionalProperties: { type: 'string' },
    };
  } else if (kind.kind === 'file') {
    schema = shape === 'projection' ? { anyOf: [fileId, expandedObject] } : fileId;
  } else if (kind.kind === 'files') {
    schema = { type: 'array', items: shape === 'projection' ? { anyOf: [fileId, expandedObject] } : fileId };
  } else if (field.type === 'alias') {
    return null;
  } else if (kind.kind === 'enum') {
    schema = { type: 'string', enum: [...new Set(kind.values)] };
  } else {
    schema = { ...(FIELD_TYPE_JSON_SCHEMA[field.type] ?? {}) };
  }

  if (field.encrypted && shape !== 'input') {
    schema = { anyOf: [schema, { const: '***', description: 'Masked: caller lacks `read_decrypted`.' }] };
  }
  if (isNullable(field)) schema = withNull(schema);
  if (field.readonly && shape !== 'input') schema = { ...schema, readOnly: true };
  return schema;
}

function addCollectionSchemas(
  schemas: Record<string, JsonSchema>,
  collection: TypegenCollection,
  base: string,
  ctx: SchemaContext,
): void {
  const userFields = collection.fields.filter((field) => !field.system);
  const ref = (suffix: string): JsonSchema => ({ $ref: `#/components/schemas/${base}.${suffix}` });

  const fieldProps: Record<string, JsonSchema> = {};
  const projectionProps: Record<string, JsonSchema> = {
    id: { ...ctx.primaryKeySchema(collection.name), readOnly: true },
    status: { type: 'string' },
    sort: { type: 'integer' },
    user_created: nullableString,
    user_updated: nullableString,
    created_at: timestamp,
    updated_at: timestamp,
  };
  const required: string[] = [];
  for (const field of userFields) {
    const item = fieldSchema(field, collection, ctx, 'item');
    const projection = fieldSchema(field, collection, ctx, 'projection');
    if (item) {
      fieldProps[field.name] = item;
      if (field.required) required.push(field.name);
    }
    if (projection) projectionProps[field.name] = projection;
  }

  schemas[`${base}.Fields`] = {
    type: 'object',
    description: `User fields of \`${collection.name}\`.`,
    properties: fieldProps,
    ...(required.length > 0 ? { required } : {}),
  };
  schemas[`${base}.Item`] = {
    type: 'object',
    properties: {
      id: { ...ctx.primaryKeySchema(collection.name), readOnly: true },
      status: { type: 'string', description: '`draft`, `published`, `archived`, or a custom workflow value.' },
      sort: { type: 'integer' },
      data: ref('Fields'),
      publishAt: nullableTimestamp,
      unpublishAt: nullableTimestamp,
      userCreated: nullableString,
      userUpdated: nullableString,
      createdAt: { ...timestamp, readOnly: true },
      updatedAt: { ...timestamp, readOnly: true },
    },
    required: ['id', 'status', 'data'],
  };
  schemas[`${base}.Projection`] = {
    type: 'object',
    description: 'Flat shape returned when the request passes `fields=`; only requested keys are present.',
    properties: projectionProps,
  };

  const inputSchema = (withRequired: boolean): JsonSchema => {
    const props: Record<string, JsonSchema> = {};
    const req: string[] = [];
    for (const field of userFields) {
      if (field.readonly || field.generated) continue;
      const schema = fieldSchema(field, collection, ctx, 'input');
      if (!schema) continue;
      props[field.name] = schema;
      if (withRequired && field.required) req.push(field.name);
    }
    return {
      type: 'object',
      properties: {
        data: { type: 'object', properties: props, ...(req.length > 0 ? { required: req } : {}) },
        status: { type: 'string' },
        sort: { type: 'integer' },
        publishAt: nullableTimestamp,
        unpublishAt: nullableTimestamp,
      },
      ...(withRequired ? { required: ['data'] } : {}),
    };
  };
  schemas[`${base}.CreateInput`] = inputSchema(true);
  schemas[`${base}.UpdateInput`] = inputSchema(false);

  const itemOrProjection: JsonSchema = { anyOf: [ref('Item'), ref('Projection')] };
  schemas[`${base}.Response`] = {
    type: 'object',
    description: 'Single-item envelope.',
    properties: { data: itemOrProjection },
    required: ['data'],
  };
  schemas[`${base}.ListResponse`] = {
    type: 'object',
    description: 'A page of items.',
    properties: {
      data: { type: 'array', items: itemOrProjection },
      meta: { $ref: '#/components/schemas/PaginationMeta' },
    },
    required: ['data'],
  };
}
